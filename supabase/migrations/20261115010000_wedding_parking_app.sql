-- Keep profile IDs linked to Supabase Auth IDs, including existing legacy profiles.
CREATE OR REPLACE FUNCTION public.handle_new_staff_profile()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
    INSERT INTO public.profiles (id, auth_uid, full_name, email, role)
    VALUES (NEW.id, NEW.id,
            COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'name', split_part(NEW.email,'@',1)),
            NEW.email, 'pending')
    ON CONFLICT (auth_uid) DO UPDATE
       SET email=EXCLUDED.email,
           full_name=COALESCE(EXCLUDED.full_name, public.profiles.full_name);
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_staff_profile();

