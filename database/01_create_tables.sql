-- Canonical schema for Smart Wedding Parking.
-- Safe to re-run: all table/column/index operations preserve existing rows.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

GRANT USAGE ON SCHEMA public TO authenticated, service_role;

CREATE TABLE IF NOT EXISTS public.profiles (
    id uuid PRIMARY KEY,
    auth_uid uuid UNIQUE,
    full_name text,
    email text UNIQUE,
    role text NOT NULL DEFAULT 'pending',
    created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS auth_uid uuid;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS full_name text;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS email text;
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS role text DEFAULT 'pending';
ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS created_at timestamptz DEFAULT now();
DO $$
DECLARE role_type text;
BEGIN
    SELECT data_type INTO role_type
    FROM information_schema.columns
    WHERE table_schema='public' AND table_name='profiles' AND column_name='role';
    IF role_type IS DISTINCT FROM 'text' THEN
        ALTER TABLE public.profiles ALTER COLUMN role DROP DEFAULT;
        ALTER TABLE public.profiles ALTER COLUMN role TYPE text USING role::text;
    END IF;
END $$;
ALTER TABLE public.profiles ALTER COLUMN role SET DEFAULT 'pending';
UPDATE public.profiles SET auth_uid=id WHERE auth_uid IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS profiles_auth_uid_uidx ON public.profiles(auth_uid);

CREATE TABLE IF NOT EXISTS public.wedding_events (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name text NOT NULL,
    event_date date NOT NULL,
    status text NOT NULL DEFAULT 'planned'
        CHECK (status IN ('planned','active','completed')),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.parking_slots (
    slot_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot_number integer NOT NULL UNIQUE,
    status text NOT NULL DEFAULT 'available'
        CHECK (status IN ('available','unavailable')),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Upgrade a legacy vehicles table in place if it exists; never drop old vehicle records.
CREATE TABLE IF NOT EXISTS public.vehicles (
    vehicle_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number text NOT NULL,
    vehicle_type text NOT NULL DEFAULT 'other',
    guest_name text,
    guest_contact text,
    created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS vehicle_id bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS registration_number text;
ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS vehicle_type text NOT NULL DEFAULT 'other';
ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS guest_name text;
ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS guest_contact text;
ALTER TABLE public.vehicles ADD COLUMN IF NOT EXISTS created_at timestamptz DEFAULT now();
-- Older installations also have legacy vehicle fields. Keep them and their existing data,
-- but do not require them for app inserts. Generate the legacy UUID primary key automatically.
DO $$
DECLARE legacy_column record;
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema='public' AND table_name='vehicles'
                 AND column_name='id' AND data_type='uuid') THEN
        ALTER TABLE public.vehicles ALTER COLUMN id SET DEFAULT gen_random_uuid();
    END IF;
    FOR legacy_column IN
        SELECT column_name FROM information_schema.columns
        WHERE table_schema='public' AND table_name='vehicles'
          AND column_name IN ('owner_id','vehicle_number','model','capacity')
    LOOP
        EXECUTE format('ALTER TABLE public.vehicles ALTER COLUMN %I DROP NOT NULL', legacy_column.column_name);
    END LOOP;
END $$;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema='public' AND table_name='vehicles' AND column_name='plate_number') THEN
        EXECUTE 'UPDATE public.vehicles SET registration_number = plate_number WHERE registration_number IS NULL';
        EXECUTE 'ALTER TABLE public.vehicles ALTER COLUMN plate_number DROP NOT NULL';
    END IF;
    UPDATE public.vehicles
    SET registration_number = 'LEGACY-' || vehicle_id::text
    WHERE registration_number IS NULL OR btrim(registration_number) = '';
END $$;
ALTER TABLE public.vehicles ALTER COLUMN registration_number SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS vehicles_vehicle_id_uidx ON public.vehicles(vehicle_id);
CREATE UNIQUE INDEX IF NOT EXISTS vehicles_registration_number_uidx ON public.vehicles(registration_number);

CREATE TABLE IF NOT EXISTS public.parking_sessions (
    session_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id bigint NOT NULL REFERENCES public.wedding_events(event_id),
    vehicle_id bigint NOT NULL REFERENCES public.vehicles(vehicle_id),
    slot_id bigint NOT NULL REFERENCES public.parking_slots(slot_id),
    entry_time timestamptz NOT NULL DEFAULT now(),
    exit_time timestamptz,
    entry_recorded_by uuid REFERENCES public.profiles(id),
    exit_recorded_by uuid REFERENCES public.profiles(id)
);

CREATE TABLE IF NOT EXISTS public.parking_events (
    parking_event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL REFERENCES public.parking_sessions(session_id) ON DELETE CASCADE,
    action_type text NOT NULL CHECK (action_type IN ('entry','exit')),
    performed_by uuid REFERENCES public.profiles(id),
    notes text,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS parking_sessions_event_entry_idx
    ON public.parking_sessions(event_id, entry_time DESC);
CREATE UNIQUE INDEX IF NOT EXISTS parking_sessions_one_active_vehicle_uidx
    ON public.parking_sessions(vehicle_id) WHERE exit_time IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS parking_sessions_one_active_slot_uidx
    ON public.parking_sessions(slot_id) WHERE exit_time IS NULL;

-- A definer helper avoids recursive RLS checks when policies need to inspect profiles.
CREATE OR REPLACE FUNCTION public.is_parking_staff()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.profiles p
        WHERE (p.id = (SELECT auth.uid()) OR p.auth_uid = (SELECT auth.uid()))
          AND p.role IN ('admin','manager','attendant')
    );
$$;
REVOKE ALL ON FUNCTION public.is_parking_staff() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.is_parking_staff() TO authenticated, service_role;

-- Replace stale policies on these app tables so old permissive policies cannot bypass access rules.
DO $$
DECLARE p record;
BEGIN
    FOR p IN SELECT schemaname, tablename, policyname FROM pg_policies
             WHERE schemaname='public'
               AND tablename IN ('profiles','wedding_events','vehicles','parking_slots','parking_sessions','parking_events')
    LOOP
        EXECUTE format('DROP POLICY %I ON %I.%I', p.policyname, p.schemaname, p.tablename);
    END LOOP;
END $$;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.wedding_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vehicles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.parking_slots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.parking_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.parking_events ENABLE ROW LEVEL SECURITY;

CREATE POLICY profiles_read_self ON public.profiles FOR SELECT TO authenticated
    USING (id=(SELECT auth.uid()) OR auth_uid=(SELECT auth.uid()));
CREATE POLICY wedding_events_staff_read ON public.wedding_events FOR SELECT TO authenticated
    USING (public.is_parking_staff());
CREATE POLICY wedding_events_staff_insert ON public.wedding_events FOR INSERT TO authenticated
    WITH CHECK (public.is_parking_staff());
CREATE POLICY wedding_events_staff_update ON public.wedding_events FOR UPDATE TO authenticated
    USING (public.is_parking_staff()) WITH CHECK (public.is_parking_staff());
CREATE POLICY wedding_events_staff_delete ON public.wedding_events FOR DELETE TO authenticated
    USING (public.is_parking_staff());
CREATE POLICY vehicles_staff_read ON public.vehicles FOR SELECT TO authenticated
    USING (public.is_parking_staff());
CREATE POLICY vehicles_staff_insert ON public.vehicles FOR INSERT TO authenticated
    WITH CHECK (public.is_parking_staff());
CREATE POLICY vehicles_staff_update ON public.vehicles FOR UPDATE TO authenticated
    USING (public.is_parking_staff()) WITH CHECK (public.is_parking_staff());
CREATE POLICY parking_slots_staff_read ON public.parking_slots FOR SELECT TO authenticated
    USING (public.is_parking_staff());
CREATE POLICY parking_slots_staff_update ON public.parking_slots FOR UPDATE TO authenticated
    USING (public.is_parking_staff()) WITH CHECK (public.is_parking_staff());
CREATE POLICY parking_sessions_staff_read ON public.parking_sessions FOR SELECT TO authenticated
    USING (public.is_parking_staff());
CREATE POLICY parking_events_staff_read ON public.parking_events FOR SELECT TO authenticated
    USING (public.is_parking_staff());

-- Do not expose the app tables to unauthenticated clients. Flask uses service_role;
-- browser pages use the authenticated role after a staff login.
REVOKE ALL ON TABLE public.profiles, public.wedding_events, public.vehicles,
    public.parking_slots, public.parking_sessions, public.parking_events FROM anon, PUBLIC;
GRANT SELECT ON public.profiles TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.wedding_events TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.vehicles TO authenticated;
GRANT SELECT, UPDATE ON public.parking_slots TO authenticated;
GRANT SELECT ON public.parking_sessions, public.parking_events TO authenticated;
GRANT ALL ON public.profiles, public.wedding_events, public.vehicles,
    public.parking_slots, public.parking_sessions, public.parking_events TO service_role;
DO $$
DECLARE t text; seq text;
BEGIN
    FOREACH t IN ARRAY ARRAY['wedding_events','vehicles','parking_slots','parking_sessions','parking_events'] LOOP
        seq := pg_get_serial_sequence(format('public.%I', t), CASE t
            WHEN 'wedding_events' THEN 'event_id'
            WHEN 'vehicles' THEN 'vehicle_id'
            WHEN 'parking_slots' THEN 'slot_id'
            WHEN 'parking_sessions' THEN 'session_id'
            ELSE 'parking_event_id' END);
        IF seq IS NOT NULL THEN
            EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %s TO authenticated, service_role', seq);
        END IF;
    END LOOP;
END $$;

-- Keep profile IDs linked to Supabase Auth IDs, including existing legacy profiles.
CREATE OR REPLACE FUNCTION public.handle_new_staff_profile()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
    INSERT INTO public.profiles (id, auth_uid, full_name, email, role)
    VALUES (NEW.id, NEW.id,
            COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'name', split_part(NEW.email,'@',1)),
            NEW.email, 'pending')
    ON CONFLICT (auth_uid) DO UPDATE
       SET email=EXCLUDED.email,
           full_name=COALESCE(EXCLUDED.full_name, public.profiles.full_name);
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_staff_profile();

